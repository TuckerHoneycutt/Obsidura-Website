def _production_url() -> str:
    return f"https://{identity.production_domain()}"


#: Every placeholder, and where its value comes from. All of them route through
#: `identity`, so production's hostname appears in neither this file nor the
#: manifest — the same rule Task 1 and Task 2 hold themselves to, for the same
#: reason: a literal is correct on exactly one host.
_SUBSTITUTIONS = {
    "production_url": _production_url,
    "production_domain": identity.production_domain,
}


def _substitute(value: str) -> str:
    for name, resolve in _SUBSTITUTIONS.items():
        token = "{" + name + "}"
        if token in value:
            value = value.replace(token, resolve())
    leftover = _PLACEHOLDER_PATTERN.findall(value)
    if leftover:
        raise ExclusionError(
            f"{value!r} still contains unresolved placeholder(s) {leftover}."
        )
    return value


def env_overrides_for(
    excluded: Iterable[str], manifest: Mapping[str, ServiceRule] | None = None
) -> dict[str, str]:
    """`on_exclude.env` for the whole closure, with placeholders resolved.

    Handed to `envfile.render_branch_env(exclusions_env=…)`, which applies it
    LAST so the result is still seen by every hazard rule in Task 2's checker.

    Two rules that disagree about one variable is a manifest bug, not a
    last-one-wins: the branch would be wired one way or the other depending on
    dictionary order.
    """
    manifest = _manifest(manifest)
    overrides: dict[str, str] = {}
    origin: dict[str, str] = {}
    for name in sorted(closure(excluded, manifest)):
        rule = manifest.get(name)
        if rule is None:
            continue
        for key, raw in rule.env.items():
            value = _substitute(raw)
            if key in overrides and overrides[key] != value:
                raise ExclusionError(
                    f"excluding {sorted(set(excluded))} sets {key} to both "
                    f"{overrides[key]!r} (from {origin[key]}) and {value!r} "
                    f"(from {name}); the manifest must not disagree with itself."
                )
            overrides[key] = value
            origin[key] = name
    return overrides


def production_reference_exemptions(
    excluded: Iterable[str],
    manifest: Mapping[str, ServiceRule] | None = None,
    domain: str | None = None,
) -> frozenset[str]:
    """Variables this exclusion set deliberately points at production.

    Task 2's `inherited_hazards` rule 1 refuses ANY branch variable whose value
    embeds production's domain, and that refusal is the most valuable thing in
    Task 2 (finding N1). `--without forgejo` is the one case where naming
    production is the intent rather than the bug (spec §5.4), so the exemption
    is derived from the values actually produced — never a hand-kept list — and
    it is EMPTY whenever nothing is excluded.
    """
    domain = domain or identity.production_domain()
    return frozenset(
        key
        for key, value in env_overrides_for(excluded, manifest).items()
        if domain in value
    )


