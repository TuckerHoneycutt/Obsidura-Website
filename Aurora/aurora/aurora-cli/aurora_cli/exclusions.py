def profiles_for(
    excluded: Iterable[str], manifest: Mapping[str, ServiceRule] | None = None
) -> str:
    """The Compose profile list an excluded service is parked behind.

    Comma-separated, matching `COMPOSE_PROFILES`' own spelling, so a future
    scheme can widen it without changing the renderer. Empty when nothing is
    excluded — and empty is load-bearing, not cosmetic: a service rendered with
    `profiles: []` has NO profile and therefore always starts, so this
    returning `""` for a non-empty exclusion set would produce an overlay that
    excludes nothing while looking exactly right.

    Never emits `agents`. That profile starts every developer's agent (spec
    D7), and the branch `.env`'s COMPOSE_PROFILES is the union of this and the
    per-developer profiles — so a collision here would be a silent
    over-provisioning rather than an error.
    """
    return EXCLUDED_PROFILE if closure(excluded, manifest) else ""


def branch_profiles(
    agent_profiles: str | Iterable[str] = (),
    excluded: Iterable[str] = (),
    manifest: Mapping[str, ServiceRule] | None = None,
) -> str:
    """The branch's COMPOSE_PROFILES: the agent profiles, and nothing else.

    Exists so the union is written down once and can be asserted on, rather
    than being an unwritten assumption. Under the opt-out scheme the exclusion
    machinery contributes NOTHING to COMPOSE_PROFILES — it removes services by
    parking them behind a profile that is never activated — and this function
    refuses to let `EXCLUDED_PROFILE` in, because if it ever appeared every
    excluded service would come straight back with no error anywhere.
    """
    if isinstance(agent_profiles, str):
        wanted = [p.strip() for p in agent_profiles.split(",") if p.strip()]
    else:
        wanted = [p.strip() for p in agent_profiles if p.strip()]
    parked = {p for p in profiles_for(excluded, manifest).split(",") if p}
    collision = sorted(set(wanted) & parked)
    if collision:
        raise ExclusionError(
            f"COMPOSE_PROFILES would activate {collision}, which is where the "
            "excluded services are parked; every one of them would come back "
            "and the exclusion would silently do nothing."
        )
    return ",".join(wanted)


