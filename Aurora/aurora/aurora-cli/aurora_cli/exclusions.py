def render_exclusion_overlay(
    services: Iterable[str], manifest: Mapping[str, ServiceRule] | None = None
) -> str:
    """The text of `compose.exclude.yml` for an ALREADY-CLOSED set of services.

    Takes the closed set rather than closing it internally, so that a test can
    render exactly what an incomplete closure would produce and hand it to real
    Compose. `exclusion_overlay_for()` is the ergonomic entry point that closes
    first, and is what `branch up` should call.

    `services: {}` is emitted for an empty set rather than a bare `services:`
    key — Compose refuses the latter with "services must be a mapping".
    """
    parked = sorted(set(services))
    profiles = [p for p in profiles_for(parked, manifest).split(",") if p]
    lines = [_HEADER.format(profile=EXCLUDED_PROFILE)]
    if not parked:
        lines.append("services: {}")
    else:
        lines.append("services:")
        for name in parked:
            lines.append(f"  {name}:")
            lines.append(f"    profiles: [{', '.join(profiles)}]")
    return "\n".join(lines).rstrip("\n") + "\n"


def exclusion_overlay_for(
    excluded: Iterable[str], manifest: Mapping[str, ServiceRule] | None = None
) -> str:
    """`render_exclusion_overlay(closure(excluded))` — what `branch up` wants."""
    return render_exclusion_overlay(closure(excluded, manifest), manifest)


def exclusion_overlay_path(directory: Path) -> Path:
    return Path(directory) / EXCLUSION_OVERLAY_NAME


def write_exclusion_overlay(
    services: Iterable[str],
    directory: Path,
    manifest: Mapping[str, ServiceRule] | None = None,
) -> Path:
    """Write the overlay for an already-closed set into `directory`.

    Written ALWAYS, even when nothing is excluded, because Compose's `-f` is a
    hard error on a missing file (trap 4) and a caller that has to decide
    whether to pass `-f` is a caller that will get it wrong once.
    """
    path = exclusion_overlay_path(directory)
    path.write_text(render_exclusion_overlay(services, manifest), encoding="utf-8")
    return path
